// ============ 渲染财经列表 ============
const financeList = document.getElementById("financeList");
articleData.forEach((art, idx) => {
  const num = idx + 1;
  const card = document.createElement("div");
  card.className = "article-card";
  card.setAttribute("onclick", `openArticle(${num})`);
  card.innerHTML = `
    <h4>${art.title}</h4>
    <p class="art-desc">点击阅读全文</p>
    <div class="art-info">
      <span>${art.date}</span>
      <span>阅读 ${art.view}</span>
    </div>
  `;
  financeList.appendChild(card);
});

// ============ 切换页面 ============
function goTo(pageId) {
  document.querySelectorAll(".page").forEach(p => p.classList.remove("active"));
  document.getElementById(pageId).classList.add("active");
  document.querySelectorAll(".nav-item").forEach(n => n.classList.remove("active"));
  document.querySelector(`.nav-item[href="#${pageId}"]`).classList.add("active");
}

// ============ 打开文章弹窗 ============
function openArticle(num) {
  const idx = num - 1;
  const art = articleData[idx];
  document.getElementById("artTitle").innerText = art.title;
  document.getElementById("artContent").innerText = art.content;
  document.getElementById("popDate").innerText = "发布时间：" + art.date;
  document.getElementById("popView").innerText = "浏览量：" + art.view;
  document.getElementById("popup").style.display = "flex";
  document.body.style.overflow = "hidden";
}

// ============ 关闭弹窗 ============
function closeArticle() {
  document.getElementById("popup").style.display = "none";
  document.body.style.overflow = "auto";
}
